import { test, expect } from "@playwright/test";

async function login(page, expectStories = true) {
  await page.goto("/");
  await page.getByRole("tab", { name: "Login", exact: true }).click();
  await page.getByLabel("Username", { exact: true }).fill("pa4_alex");
  await page.getByLabel("Password", { exact: true }).fill("PA4-demo-2026!");
  await page.getByRole("button", { name: "Log In", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Signed In" })).toBeVisible();
  await page.getByLabel("Selected Project").selectOption({ label: "PA4 Campus Events" });
  if (expectStories) await expect(page.getByRole("article", { name: "View campus event details", exact: true })).toBeVisible();
}

test("create, cancel edit, save, reopen, confirm delete, and refresh preserve the correct data", async ({ page }) => {
  await login(page);
  const progress = page.getByRole("progressbar", { name: "Project completion" });
  const blair = page.locator(".member-item").filter({ hasText: "pa4_blair" });
  await expect(page.getByText("1 of 3 stories Done", { exact: true })).toBeVisible();
  await expect(progress).toHaveAttribute("value", "1");
  await expect(progress).toHaveAttribute("max", "3");
  await expect(blair.getByText("2 assigned stories", { exact: true })).toBeVisible();
  const form = page.getByRole("form", { name: "Create Story", exact: true });
  const assignees = await form.getByLabel("Assigned Member").locator("option").allTextContents();
  expect(assignees.join(" ")).toContain("pa4_alex");
  expect(assignees.join(" ")).toContain("pa4_blair");
  expect(assignees.join(" ")).not.toContain("pa4_casey");
  await form.getByLabel("Story Title").fill("Browser test story");
  await form.getByLabel("Story Description").fill("As a student, I want a browser test, so that I can verify persistence.");
  await form.getByLabel("Story Priority").selectOption("Low");
  await form.getByLabel("Assigned Member").selectOption({ label: "Blair Chen (pa4_blair)" });
  await form.getByRole("button", { name: "Create Story", exact: true }).click();
  const card = page.getByRole("article", { name: "Browser test story", exact: true });
  await expect(card).toContainText("To Do");
  await expect(card).toContainText("pa4_blair");
  await expect(page.getByText("1 of 4 stories Done", { exact: true })).toBeVisible();
  await expect(blair.getByText("3 assigned stories", { exact: true })).toBeVisible();
  await card.getByRole("button", { name: "Edit", exact: true }).click();
  let edit = page.getByRole("form", { name: "Edit Story", exact: true });
  await edit.getByLabel("Story Title").fill("Unsaved title");
  await edit.getByRole("button", { name: "Cancel Edit" }).click();
  await expect(card).toBeVisible();
  await expect(page.getByRole("article", { name: "Unsaved title", exact: true })).toHaveCount(0);
  await card.getByRole("button", { name: "Edit", exact: true }).click();
  edit = page.getByRole("form", { name: "Edit Story", exact: true });
  await edit.getByLabel("Story Status").selectOption("Done");
  await edit.getByLabel("Assigned Member").selectOption("");
  await edit.getByRole("button", { name: "Save Story" }).click();
  await expect(card).toContainText("Done");
  await expect(card).toContainText("Unassigned");
  await expect(page.getByText("2 of 4 stories Done", { exact: true })).toBeVisible();
  await expect(progress).toHaveAttribute("value", "2");
  await expect(blair.getByText("2 assigned stories", { exact: true })).toBeVisible();
  await page.reload();
  await login(page);
  await expect(card).toContainText("Done");
  await card.getByRole("button", { name: "Edit", exact: true }).click();
  await page.getByLabel("Story Status").selectOption("To Do");
  await page.getByRole("button", { name: "Save Story" }).click();
  await expect(card).toContainText("To Do");
  await expect(page.getByText("1 of 4 stories Done", { exact: true })).toBeVisible();
  page.once("dialog", (dialog) => dialog.dismiss());
  await card.getByRole("button", { name: "Delete", exact: true }).click();
  await expect(card).toBeVisible();
  page.once("dialog", (dialog) => dialog.accept());
  await card.getByRole("button", { name: "Delete", exact: true }).click();
  await expect(card).toHaveCount(0);
  await expect(page.getByText("1 of 3 stories Done", { exact: true })).toBeVisible();
  await expect(progress).toHaveAttribute("max", "3");
  await page.reload();
  await login(page);
  await expect(card).toHaveCount(0);
});

test("project changes clear editing and an old delayed response cannot replace the new backlog", async ({ page }) => {
  await login(page);
  await page.getByRole("article", { name: "View campus event details", exact: true }).getByRole("button", { name: "Edit", exact: true }).click();
  await page.getByLabel("Story Title").fill("Discard on switch");
  await page.getByRole("searchbox", { name: "Search stories" }).fill("campus");
  let release;
  const gate = new Promise((resolve) => { release = resolve; });
  let requested;
  const reached = new Promise((resolve) => { requested = resolve; });
  await page.route("**/api/projects/*/stories", async (route) => {
    const response = await route.fetch();
    if (route.request().method() === "GET" && (await response.json()).stories.some((story) => story.title === "Create a study group")) {
      requested();
      await gate;
    }
    await route.fulfill({ response }).catch(() => {});
  });
  await page.getByLabel("Selected Project").selectOption({ label: "PA4 Study Groups" });
  await reached;
  await expect(page.getByRole("form", { name: "Edit Story", exact: true })).toHaveCount(0);
  await expect(page.getByRole("searchbox", { name: "Search stories" })).toHaveValue("");
  await page.getByLabel("Selected Project").selectOption({ label: "PA4 Campus Events" });
  await expect(page.getByRole("article", { name: "View campus event details", exact: true })).toBeVisible();
  release();
  await expect(page.getByRole("article", { name: "Create a study group", exact: true })).toHaveCount(0);
  await expect(page.getByLabel("Story Title")).toHaveValue("");
  await page.unrouteAll({ behavior: "wait" });
  await expect(page.getByRole("article", { name: "View campus event details", exact: true })).toBeVisible();
  await expect(page.getByRole("article", { name: "Create a study group", exact: true })).toHaveCount(0);
  await page.getByLabel("Selected Project").selectOption({ label: "PA4 Study Groups" });
  await expect(page.getByRole("article", { name: "Create a study group", exact: true })).toBeVisible();
  const options = page.getByRole("combobox", { name: "Assigned Member", exact: true }).locator("option");
  await expect(options).toHaveText(["Unassigned", "Casey Morgan (pa4_casey)", "Alex Rivera (pa4_alex)"]);
  await expect(page.getByText("1 of 2 stories Done", { exact: true })).toBeVisible();
  await expect(page.locator(".member-item").filter({ hasText: "pa4_alex" }).getByText("0 assigned stories", { exact: true })).toBeVisible();
});

test("title, priority, status, and assignee filters combine without changing project totals", async ({ page }) => {
  await login(page);
  const search = page.getByRole("searchbox", { name: "Search stories" });
  const priority = page.getByRole("combobox", { name: "Filter priority", exact: true });
  const status = page.getByRole("combobox", { name: "Filter status", exact: true });
  const assignee = page.getByRole("combobox", { name: "Filter assignee", exact: true });
  const cards = page.getByRole("article");
  const summary = page.getByRole("region", { name: "Project progress", exact: true });
  await expect(cards).toHaveCount(3);
  await expect(priority).toHaveValue("");
  await expect(status).toHaveValue("");
  await expect(assignee).toHaveValue("");
  await expect(summary.getByRole("term")).toHaveText(["To Do", "In Progress", "Done"]);
  await expect(summary.getByRole("definition")).toHaveText(["1", "1", "1"]);
  await search.fill("  CAMPUS EVENT  ");
  await expect(cards).toHaveCount(1);
  await expect(cards).toHaveAttribute("aria-label", "View campus event details");
  await search.fill("");
  await priority.selectOption("Low");
  await status.selectOption("Done");
  await assignee.selectOption({ label: "Blair Chen (pa4_blair)" });
  await expect(cards).toHaveCount(1);
  await expect(cards).toHaveAttribute("aria-label", "Save a favorite event");
  await expect(page.getByText("Showing 1 of 3 stories", { exact: true })).toBeVisible();
  await expect(summary).toContainText("1 of 3 stories Done");
  await expect(page.locator(".member-item").filter({ hasText: "pa4_blair" }).getByText("2 assigned stories", { exact: true })).toBeVisible();
  await assignee.selectOption("unassigned");
  await expect(cards).toHaveCount(0);
  await expect(page.getByText("No stories match these filters. Clear filters to show all stories.")).toBeVisible();
  await page.getByRole("button", { name: "Clear filters", exact: true }).click();
  await expect(cards).toHaveCount(3);
  await expect(priority).toHaveValue("");
  await expect(status).toHaveValue("");
  await expect(assignee).toHaveValue("");
  await status.selectOption("In Progress");
  await expect(cards).toHaveCount(1);
  await expect(cards).toHaveAttribute("aria-label", "Filter upcoming events");
  await status.selectOption("");
  await assignee.selectOption({ label: "Blair Chen (pa4_blair)" });
  await expect(cards).toHaveCount(2);
  await page.getByLabel("Selected Project").selectOption({ label: "PA4 Study Groups" });
  await expect(assignee).toHaveValue("");
  await expect(cards).toHaveCount(2);
  await assignee.selectOption("unassigned");
  await expect(cards).toHaveCount(1);
  await expect(cards).toHaveAttribute("aria-label", "Find available groups");
  await expect(assignee.locator("option")).toHaveText(["All assignees", "Unassigned", "Casey Morgan (pa4_casey)", "Alex Rivera (pa4_alex)"]);
});

